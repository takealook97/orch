// spliceBlock replaces the marked block, or appends it when no markers exist.
func spliceBlock(doc, block string) string {
	full := markBegin + "\n" + strings.TrimSpace(block) + "\n" + markEnd
	b := strings.Index(doc, "<!-- orch:begin")
	e := strings.Index(doc, markEnd)
	if b >= 0 && e > b {
		return doc[:b] + full + doc[e+len(markEnd):]
	}
	if doc != "" && !strings.HasSuffix(doc, "\n") {
		doc += "\n"
	}
	if doc != "" {
		doc += "\n"
	}
	return doc + full + "\n"
}

func extractBlock(doc string) (string, bool) {
	b := strings.Index(doc, markBegin)
	e := strings.Index(doc, markEnd)
	if b < 0 || e < b {
		return "", false
	}
	return strings.TrimSpace(doc[b+len(markBegin) : e]), true
}

func backup(dir, path string) error {
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	rel := strings.TrimPrefix(path, home()+"/")
	dest := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(dest), 0700); err != nil {
		return err
	}
	if info.IsDir() {
		return exec.Command("cp", "-R", path, dest).Run()
	}
	if info.Mode()&os.ModeSymlink != 0 {
		target, _ := os.Readlink(path)
		return os.WriteFile(dest+".symlink", []byte(target+"\n"), 0600)
	}
	in, err := os.Open(path)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.Create(dest)
	if err != nil {
		return err
	}
	defer out.Close()
	_, err = io.Copy(out, in)
	return err
}

func readJSONFile(path string) (map[string]any, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return map[string]any{}, nil
	}
	if err != nil {
		return nil, err
	}
	var m map[string]any
	if err := json.Unmarshal(data, &m); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if err := validHookConfig(m); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return m, nil
}

func writeJSONFile(path string, m map[string]any) error {
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		return err
	}
	return atomicStateWrite(path, append(data, '\n'))
}

var ownHook = regexp.MustCompile(`/orch' hook (claude|claude-prompt|codex|codex-prompt|agy)$`)

func hookCommand(bin, cli string) string { return fmt.Sprintf("'%s' hook %s", bin, cli) }

// ensureGroupedHook adds a PreToolUse group (Claude/Codex shape) unless one already runs `orch hook`.
func ensureGroupedHook(hooks map[string]any, matcher, command string, owners ...string) bool {
	list, _ := hooks["PreToolUse"].([]any)
	for i, g := range list {
		gm, _ := g.(map[string]any)
		inner, _ := gm["hooks"].([]any)
		for _, h := range inner {
			hm, _ := h.(map[string]any)
			if c, _ := hm["command"].(string); hookOwned(c, owners) {
				changed := matcher != "" && gm["matcher"] != matcher
				hm["command"] = command
				if matcher != "" {
					gm["matcher"] = matcher
				}
				list[i] = gm
				hooks["PreToolUse"] = list
				return changed
			}
		}
	}
	group := map[string]any{"hooks": []any{map[string]any{"type": "command", "command": command, "timeout": 10}}}
	if matcher != "" {
		group["matcher"] = matcher
	}
	hooks["PreToolUse"] = append(list, group)
	return true
}

type installReport struct{ lines []string }

func (r *installReport) add(format string, a ...any) {
	r.lines = append(r.lines, fmt.Sprintf(format, a...))
}

func install(repo string, dry bool) (*installReport, error) {
	rep := &installReport{}
	repo, _ = filepath.Abs(repo)
	if _, err := os.Stat(filepath.Join(repo, "skill", "SKILL.md")); err != nil {
		return nil, fmt.Errorf("not a repository path: %s (skill/SKILL.md missing). specify with --repo", repo)
	}
	bin, err := os.Executable()
	if err != nil {
		return nil, err
	}
	bin, _ = filepath.EvalSymlinks(bin)
	ownership, err := loadOwnership()
	if err != nil {
		return rep, err
	}
	if ownership != nil && ownership.Repo != repo {
		return rep, fmt.Errorf("another repository owns this installation: %s", ownership.Repo)
	}
	linked := filepath.Join(home(), ".local", "bin", "orch")
	if info, e := os.Lstat(linked); e == nil {
		resolved, re := filepath.EvalSymlinks(linked)
		if info.IsDir() || re != nil || (resolved != bin && resolved != filepath.Join(repo, "bin/orch")) {
			return rep, fmt.Errorf("foreign binary/link preserved: %s", linked)
		}
		bin = linked
	} else if !os.IsNotExist(e) {
		return rep, e
	}
	owners := func(cli string) []string {
		out := []string{hookCommand(bin, cli), hookCommand(filepath.Join(home(), ".local/bin/orch"), cli), hookCommand(filepath.Join(repo, "bin/orch"), cli)}
		if ownership != nil {
			out = append(out, hookCommand(ownership.Bin, cli))
		}
		return out
	}
	for _, link := range skillLinks() {
		if err := safeInstallLink(link, filepath.Join(repo, "skill")); err != nil {
			return rep, err
		}
	}
	if err := safeInstallLink(filepath.Join(orchHome(), "playbooks"), filepath.Join(repo, "playbooks")); err != nil {
		return rep, err
	}
	// Validate all inputs before writing any constitution or hook config.
	for _, p := range append(constitutionFiles(), claudeSettings(), codexHooks(), agyHooks()) {
		if info, e := os.Lstat(p); e == nil && !info.Mode().IsRegular() {
			return rep, fmt.Errorf("non-regular config preserved: %s", p)
		}
	}
	for _, p := range []string{claudeSettings(), codexHooks(), agyHooks()} {
		if s, e := readJSONFile(p); e != nil {
			return rep, e
		} else if p == agyHooks() {
			if old, ok := s["orch-guard"]; ok {
				valid := false
				for _, cmd := range owners("agy") {
					want := map[string]any{"PreToolUse": []any{map[string]any{"matcher": "*", "hooks": []any{map[string]any{"type": "command", "command": cmd, "timeout": float64(10)}}}}}
					if reflect.DeepEqual(old, want) {
						valid = true
					}
				}
				if !valid {
					return rep, fmt.Errorf("foreign or modified orch-guard preserved: %s", p)
				}
			}
		}
	}
	for _, p := range constitutionFiles() {
		b, e := os.ReadFile(p)
		if e != nil && !os.IsNotExist(e) {
			return rep, e
		}
		s := string(b)
		beg, end := strings.Count(s, "<!-- orch:begin"), strings.Count(s, markEnd)
		if beg != 0 || end != 0 {
			if _, ok := extractBlock(s); beg != 1 || end != 1 || !ok {
				return rep, fmt.Errorf("ambiguous markers preserved: %s", p)
			}
		}
	}
	// Back up a target only right before it changes, so a rerun with nothing to do
	// leaves no empty backup directory behind.
	bdir := filepath.Join(orchHome(), "backups", time.Now().Format("20060102-150405.000000000"))
	backedUp := false
	save := func(t string) error {
		if dry {
			return nil
		}
		if err := backup(bdir, t); err != nil {
			return fmt.Errorf("backup failed %s: %w", t, err)
		}
		if !backedUp {
			backedUp = true
			rep.add("backup: %s", bdir)
		}
		return nil
	}
	// writeHooks writes s only when its JSON differs from what is on disk.
	writeHooks := func(path string, before []byte, s map[string]any) (bool, error) {
		after, err := json.MarshalIndent(s, "", "  ")
		if err != nil {
			return false, err
		}
		// Compare content, not bytes: other tools (herdr integration) rewrite the same
		// files with their own key order and indentation.
		var was, now any
		if json.Unmarshal(before, &was) == nil && json.Unmarshal(after, &now) == nil && reflect.DeepEqual(was, now) {
			return false, nil
		}
		if err := save(path); err != nil {
			return false, err
		}
		if dry {
			return true, nil
		}
		return true, writeJSONFile(path, s)
	}

	// ① constitution
	for _, f := range constitutionFiles() {
		data, _ := os.ReadFile(f)
		next := spliceBlock(string(data), constitutionBlock)
		if next == string(data) {
			rep.add("constitution up to date: %s", f)
			continue
		}
		rep.add("constitution updated: %s", f)
		if err := save(f); err != nil {
			return nil, err
		}
		if !dry {
			if err := os.MkdirAll(filepath.Dir(f), 0700); err != nil {
				return nil, err
			}
			if err := os.WriteFile(f, []byte(next), 0644); err != nil {
				return nil, err
			}
		}
	}

	// ③ hooks
	if s, err := readJSONFile(claudeSettings()); err == nil {
		hooks, _ := s["hooks"].(map[string]any)
		if hooks == nil {
			hooks = map[string]any{}
		}
		added := ensureGroupedHook(hooks, "Agent|Task|Workflow|Bash|Edit|Write|MultiEdit|NotebookEdit", hookCommand(bin, "claude"), owners("claude")...)
		ensurePromptHook(hooks, hookCommand(bin, "claude-prompt"), owners("claude-prompt")...)
		s["hooks"] = hooks
		before, _ := os.ReadFile(claudeSettings())
		changed, err := writeHooks(claudeSettings(), before, s)
		if err != nil {
			return nil, err
		}
		rep.add("Claude hook %s: %s", hookState(added, changed), claudeSettings())
	} else {
		return nil, err
	}
	if s, err := readJSONFile(codexHooks()); err == nil {
		hooks, _ := s["hooks"].(map[string]any)
		if hooks == nil {
			hooks = map[string]any{}
		}
		added := ensureGroupedHook(hooks, "", hookCommand(bin, "codex"), owners("codex")...)
		ensurePromptHook(hooks, hookCommand(bin, "codex-prompt"), owners("codex-prompt")...)
		s["hooks"] = hooks
		before, _ := os.ReadFile(codexHooks())
		changed, err := writeHooks(codexHooks(), before, s)
		if err != nil {
			return nil, err
		}
		rep.add("Codex hook %s: %s", hookState(added, changed), codexHooks())
	} else {
		return nil, err
	}
	if s, err := readJSONFile(agyHooks()); err == nil {
		s["orch-guard"] = map[string]any{
			"PreToolUse": []any{map[string]any{
				"matcher": "*",
				"hooks":   []any{map[string]any{"type": "command", "command": hookCommand(bin, "agy"), "timeout": 10}},
			}},
		}
		before, _ := os.ReadFile(agyHooks())
		changed, err := writeHooks(agyHooks(), before, s)
		if err != nil {
			return nil, err
		}
		rep.add("agy hook %s: %s", hookState(false, changed), agyHooks())
	} else {
		return nil, err
	}

	// ④ skill (one source, symlinked) and playbooks
	skillSrc := filepath.Join(repo, "skill")
	for _, link := range skillLinks() {
		if cur, err := os.Readlink(link); err == nil && cur == skillSrc {
			rep.add("skill link up to date: %s", link)
			continue
		}
		rep.add("skill link: %s → %s", link, skillSrc)
		if err := save(link); err != nil {
			return nil, err
		}
		if !dry {
			if err := os.Remove(link); err != nil && !os.IsNotExist(err) {
				return nil, err
			}
			if err := os.MkdirAll(filepath.Dir(link), 0700); err != nil {
				return nil, err
			}
			if err := os.Symlink(skillSrc, link); err != nil {
				return nil, err
			}
		}
	}
	pbLink := filepath.Join(orchHome(), "playbooks")
	pbSrc := filepath.Join(repo, "playbooks")
	if cur, err := os.Readlink(pbLink); err != nil || cur != pbSrc {
		rep.add("playbook link: %s → %s", pbLink, pbSrc)
		if err := save(pbLink); err != nil {
			return nil, err
		}
		if !dry {
			if err := os.Remove(pbLink); err != nil && !os.IsNotExist(err) {
				return nil, err
			}
			_ = os.MkdirAll(orchHome(), 0700)
			if err := os.Symlink(pbSrc, pbLink); err != nil {
				return nil, err
			}
		}
	}
	if !dry {
		if ownership != nil && (ownership.Bin != bin || ownership.Block != constitutionBlock) {
			if err := save(ownershipPath()); err != nil {
				return rep, err
			}
		}
		if err := saveOwnership(repo, bin); err != nil {
			return rep, err
		}
	}
	return rep, nil
}

func hookState(added, changed bool) string {
	switch {
	case added:
		return "added"
	case changed:
		return "updated"
	}
	return "up to date"
}

func fileExists(p string) bool { _, err := os.Stat(p); return err == nil }

type check struct {
	ok   bool
	name string
	info string
	warn bool
}

func doctor() []check {
	var out []check
	add := func(ok bool, name, info string) { out = append(out, check{ok: ok, name: name, info: info}) }
	bins := []string{"codex", "claude", "agy", "git"}
	if backend() == "app" {
		bins = append(bins, "hc", "herdr-app")
		_, err := hcRun("server", "status")
		add(err == nil, "hc server", fmt.Sprint(err))
	} else {
		bins = append(bins, "herdr")
	}
	add(inHerdr(), "backend", backend())
	for _, bin := range bins {
		p, err := exec.LookPath(bin)
		add(err == nil, "CLI "+bin, p)
	}
	key := "HERDR_PANE_ID"
	if backend() == "app" {
		key = "HC_TERMINAL_ID"
	}
	add(inHerdr(), "Herdr session", key+"="+headID())
	add(envOrch("ROLE") != "worker", "role", "ORCH_ROLE="+envOrch("ROLE"))
	want := strings.TrimSpace(constitutionBlock)
	for _, f := range constitutionFiles() {
		data, err := os.ReadFile(f)
		got, ok := extractBlock(string(data))
		switch {
		case err != nil:
			add(false, "constitution "+f, "file missing")
		case !ok:
			add(false, "constitution "+f, "orch block missing (orch install)")
		default:
			add(got == want, "constitution "+f, map[bool]string{true: "matches", false: "differs from source (orch install)"}[got == want])
		}
	}
	for cli, p := range map[string]string{"claude": claudeSettings(), "codex": codexHooks(), "agy": agyHooks()} {
		data, _ := os.ReadFile(p)
		ok := strings.Contains(string(data), "hook "+cli)
		add(ok, "hook "+cli, p)
	}
	for _, link := range skillLinks() {
		t, err := os.Readlink(link)
		add(err == nil && fileExists(filepath.Join(t, "SKILL.md")), "skill "+link, t)
	}
	pb := filepath.Join(orchHome(), "playbooks")
	errs := checkPlaybooks(pb)
	add(len(errs) == 0 && fileExists(pb), "playbook "+pb, strings.Join(errs, "; "))
	if envOrch("ACCOUNT_CMD") != "" {
		add(true, "account hook", envOrch("ACCOUNT_CMD"))
	} else {
		add(true, "account", "same (uses Head login, ORCH_ACCOUNT_CMD absent)")
	}
	for _, m := range catalog {
		vars := []string{modelVar(m)}
		if legacy := embeddedManifest.Rules.LegacyModelEnv[m.Key]; legacy != "" {
			vars = append(vars, legacy)
		}
		for _, v := range vars {
			if strings.TrimSpace(os.Getenv(v)) != "" {
				out = append(out, check{ok: true, warn: true, name: "model override " + m.Key, info: v + " shadows models.yaml/~/.orch/models.yaml; move it to ~/.orch/models.yaml"})
			}
		}
	}
	return out
}

