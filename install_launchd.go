package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"time"
)

// The nightly self-update agent: `orch update --models` every day at 03:00 (macOS only).
const launchAgentLabel = "ai.deepeet.orch-update"

func launchAgentPath() string {
	return filepath.Join(home(), "Library", "LaunchAgents", launchAgentLabel+".plist")
}

// launchdGOOS and launchctlRun are replaced in tests so launchctl is never called.
var (
	launchdGOOS  = runtime.GOOS
	launchctlRun = func(args ...string) error {
		out, err := exec.Command("launchctl", args...).CombinedOutput()
		if err != nil {
			return fmt.Errorf("launchctl %s: %w: %s", strings.Join(args, " "), err, probeExcerpt(string(out)))
		}
		return nil
	}
)

func xmlText(s string) string {
	var b bytes.Buffer
	_ = xml.EscapeText(&b, []byte(s))
	return b.String()
}

func launchAgentPlist(bin string) string {
	var env strings.Builder
	for _, key := range []string{"PATH", "ORCH_HOME"} {
		if v := os.Getenv(key); v != "" {
			fmt.Fprintf(&env, "\t\t<key>%s</key>\n\t\t<string>%s</string>\n", key, xmlText(v))
		}
	}
	log := xmlText(filepath.Join(orchHome(), "update.launchd.log"))
	return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- generated by orch install; removed by orch uninstall --apply -->
<plist version="1.0">
<dict>
	<key>Label</key>
	<string>` + launchAgentLabel + `</string>
	<key>ProgramArguments</key>
	<array>
		<string>` + xmlText(bin) + `</string>
		<string>update</string>
		<string>--models</string>
	</array>
	<key>EnvironmentVariables</key>
	<dict>
` + env.String() + `	</dict>
	<key>StartCalendarInterval</key>
	<dict>
		<key>Hour</key>
		<integer>3</integer>
		<key>Minute</key>
		<integer>0</integer>
	</dict>
	<key>StandardOutPath</key>
	<string>` + log + `</string>
	<key>StandardErrorPath</key>
	<string>` + log + `</string>
</dict>
</plist>
`
}

// launchAgentOwned reports whether the plist at path was written by orch install.
func launchAgentOwned(path string) (exists, owned bool) {
	info, err := os.Lstat(path)
	if err != nil {
		return false, false
	}
	if !info.Mode().IsRegular() {
		return true, false
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return true, false
	}
	s := string(data)
	return true, strings.Contains(s, "generated by orch install") && strings.Contains(s, "<string>"+launchAgentLabel+"</string>")
}

func launchDomain() string { return fmt.Sprintf("gui/%d", os.Getuid()) }

// installLaunchAgent writes and registers the nightly update agent, backing up first.
func installLaunchAgent(rep *installReport, bin string, dry bool, save func(string) error) error {
	if launchdGOOS != "darwin" {
		rep.add("launchd: skipped (not macOS)")
		return nil
	}
	path := launchAgentPath()
	want := launchAgentPlist(bin)
	exists, owned := launchAgentOwned(path)
	if exists && !owned {
		rep.add("preserve foreign launch agent: %s", path)
		return nil
	}
	if cur, err := os.ReadFile(path); err == nil && string(cur) == want {
		rep.add("launch agent up to date: %s", path)
		return nil
	}
	rep.add("launch agent: %s (daily 03:00 orch update --models)", path)
	if err := save(path); err != nil {
		return err
	}
	if dry {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	if err := atomicStateWrite(path, []byte(want)); err != nil {
		return err
	}
	_ = launchctlRun("bootout", launchDomain(), path)
	if err := launchctlRun("bootstrap", launchDomain(), path); err != nil {
		// The file is in place; launchd loads it at next login even if bootstrap failed now.
		rep.add("launchd: bootstrap failed (loads at next login): %v", err)
	}
	return nil
}

// uninstallLaunchAgent removes only an orch-written agent, after backing it up.
func uninstallLaunchAgent(rep *installReport, apply bool) error {
	if launchdGOOS != "darwin" {
		return nil
	}
	path := launchAgentPath()
	exists, owned := launchAgentOwned(path)
	if !exists {
		return nil
	}
	if !owned {
		rep.add("preserve foreign launch agent: %s", path)
		return nil
	}
	rep.add("remove owned content: %s", path)
	if !apply {
		return nil
	}
	bdir := filepath.Join(orchHome(), "backups", "uninstall-launchd-"+time.Now().Format("20060102-150405.000000000"))
	if err := backup(bdir, path); err != nil {
		return err
	}
	_ = launchctlRun("bootout", launchDomain(), path)
	if err := os.Remove(path); err != nil {
		return err
	}
	rep.add("backup: %s", bdir)
	return nil
}
